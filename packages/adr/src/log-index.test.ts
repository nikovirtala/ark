import { MemoryTree, renderIndex } from "@nikovirtala/ledger";
import { createTempRepo, type TempRepo } from "@nikovirtala/ledger/testing";
import { afterEach, describe, expect, it } from "vitest";
import { DEFAULT_ADR_CONFIG } from "./config.js";
import { openDecisionLog, readDecisionsFrom } from "./log.js";
import { DECISION_INDEX } from "./log-index.js";
import { NYGARD_SECTIONS, REPO_HUMAN } from "./test-support/cli.js";
import {
  decisionEvent,
  decisionFiles,
  hashOf,
  LAYOUT,
  numberingOf,
  proposedData,
} from "./test-support/events.js";
import { acceptDecision, proposeDecision, scopeDecision } from "./write.js";

const A = "a7c2m9xd";
const B = "k3f9q8a1";
const C = "m2x7p4d2";
const D = "r4tw9xd1";
const E = "zz9e4w2q";
const BODY = "# Decision\n\nText.\n";
const at = (d: string) => `2026-${d}T10:00:00Z`;
const ev = (id: string, type: string, d: string, o: Record<string, unknown> = {}) =>
  decisionEvent(id, type, { at: at(d), ...o });
const proposed = (id: string, d: string, title: string) =>
  ev(id, "proposed", d, { data: proposedData(title) });
const accepted = (id: string, d: string) =>
  ev(id, "accepted", d, { data: { body_sha256: hashOf(BODY) } });

describe("the decision index", () => {
  it("renders the groups, active first, with escaped titles linked to their bodies", async () => {
    const files = decisionFiles([
      {
        id: A,
        body: BODY,
        slug: "use-dynamodb",
        events: [
          proposed(A, "03-12", "Use DynamoDB"),
          accepted(A, "03-14"),
          ev(A, "superseded", "05-01", { data: { by: B } }),
        ],
      },
      {
        id: B,
        body: BODY,
        slug: "use-aurora-or-postgres",
        events: [proposed(B, "04-01", "Use Aurora | Postgres"), accepted(B, "05-01")],
      },
      { id: C, body: BODY, slug: "try-redis", events: [proposed(C, "05-20", "Try Redis")] },
      // Accepted, but numbering has no number for it (an unnumbered decision sorts last).
      {
        id: D,
        body: BODY,
        slug: "use-s3",
        events: [proposed(D, "02-01", "Use S3"), accepted(D, "02-02")],
      },
      {
        id: E,
        body: BODY,
        slug: "use-mongo",
        events: [
          proposed(E, "03-01", "Use Mongo"),
          ev(E, "rejected", "03-02", { reason: "No transactions." }),
        ],
      },
    ]);
    const numbering = numberingOf({ [A]: 1, [B]: 2 });
    const read = await readDecisionsFrom(new MemoryTree(files), {
      layout: LAYOUT,
      adr: DEFAULT_ADR_CONFIG,
      numbering,
    });
    const views = read.projection.views;
    expect(renderIndex(DECISION_INDEX("docs/adr", views), [...views.values()], numbering)).toBe(
      [
        "<!-- Generated by adr; do not edit. Run `adr index` to update it. -->",
        "# Architecture decisions",
        "",
        "## Accepted",
        "",
        "| Decision | Title | Status | Since |",
        "| --- | --- | --- | --- |",
        `| ADR-0002 | [Use Aurora \\| Postgres](decisions/${B}-use-aurora-or-postgres.md) | accepted | 2026-05-01 |`,
        `| ${D} | [Use S3](decisions/${D}-use-s3.md) | accepted | 2026-02-02 |`,
        "",
        "## Proposed",
        "",
        "| Decision | Title | Status | Since |",
        "| --- | --- | --- | --- |",
        `| ${C} | [Try Redis](decisions/${C}-try-redis.md) | proposed | 2026-05-20 |`,
        "",
        "## Superseded and deprecated",
        "",
        "| Decision | Title | Status | Since |",
        "| --- | --- | --- | --- |",
        `| ADR-0001 | [Use DynamoDB](decisions/${A}-use-dynamodb.md) | superseded by ADR-0002 | 2026-05-01 |`,
        "",
        "## Rejected and withdrawn",
        "",
        "| Decision | Title | Status | Since |",
        "| --- | --- | --- | --- |",
        `| ${E} | [Use Mongo](decisions/${E}-use-mongo.md) | rejected | 2026-03-02 |`,
        "",
        `<!-- ledger-index/v1 numbers: ${A}=1 ${B}=2 -->`,
        "",
      ].join("\n"),
    );
  });
});

describe("applyPlan's written", { timeout: 60_000 }, () => {
  const repos: TempRepo[] = [];
  afterEach(async () => {
    for (const r of repos.splice(0)) await r.dispose();
  });

  it("lists index.md exactly when the write wrote it, and never twice", async () => {
    const r = await createTempRepo({
      files: { "README.md": "readme\n", "docs/adr/adr.toml": '[log]\nindex = "committed"\n' },
    });
    repos.push(r);
    const log = await openDecisionLog({ cwd: r.root, gitOptions: { env: r.env } });
    const propose = (title: string, commit: boolean) =>
      proposeDecision(log, { title, sections: NYGARD_SECTIONS, actor: REPO_HUMAN }, { commit });
    const x = await propose("Use Aurora", true);
    const index = "docs/adr/index.md";
    expect(x.written.filter((p) => p === index)).toEqual([index]);
    const id = x.decision?.id ?? "";

    // A scope event doesn't change the index.
    const scoped = await scopeDecision(
      log,
      { id, op: { set: ["README.md"] }, actor: REPO_HUMAN },
      { commit: true },
    );
    expect(scoped.written).not.toContain(index);

    // Step 3 writes the commit's render, step 5 the work tree's (with Y): listed once.
    await propose("Use Redis", false);
    const accepted = await acceptDecision(log, { id, actor: REPO_HUMAN }, { commit: true });
    expect(accepted.written.filter((p) => p === index)).toEqual([index]);
  });
});
