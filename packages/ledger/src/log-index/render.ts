import type { Numbering } from "../fold/numbering.js";
import type { TreeReader } from "../git/tree.js";

/** The format of the numbers line a generated index ends with. */
export const INDEX_FORMAT = "ledger-index/v1";

/** How a tool renders its log's index (design 2b §4.2). */
export interface IndexSpec<P> {
  /** The tool named in the generated-file header, such as `"adr"`. */
  readonly tool: string;
  /** The document title, such as `"Architecture decisions"`. */
  readonly title: string;
  /** Sections in order; a view goes in the first group whose `filter` accepts it. */
  readonly groups: readonly { readonly heading: string; readonly filter: (p: P) => boolean }[];
  /** Table columns; each cell is Markdown, already escaped. */
  readonly columns: readonly { readonly heading: string; readonly cell: (p: P) => string }[];
  /** The row order within a group. */
  readonly order: (a: P, b: P) => number;
}

/** Larger index files aren't read for numbers. */
const MAX_INDEX_BYTES = 4 * 1024 * 1024;
const NUMBERS_PREFIX = `<!-- ${INDEX_FORMAT} numbers:`;
const NUMBERS_LINE =
  /^<!-- ledger-index\/v1 numbers:((?: [0-9a-hjkmnp-tv-z]{8}=[1-9][0-9]{0,8})*) -->$/;

/**
 * Backslash-escapes the characters Markdown or HTML would read in a table cell, and collapses
 * whitespace.
 */
export function escapeMarkdown(text: string): string {
  return text
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[\\|[\]*_`<>]/g, (c) => `\\${c}`);
}

const row = (cells: readonly string[]) =>
  `| ${cells.map((c) => c.replace(/\r\n|\r|\n/g, " ")).join(" | ")} |`;

/**
 * Renders a generated Markdown index: a header naming the tool (not its version, so upgrades don't
 * stale every index), the title, one table per non-empty group (`No entries yet.` when no view
 * has a group), and a last line recording `numbering`'s numbers for shallow clones. LF line
 * endings, ending in one newline.
 */
export function renderIndex<P>(
  spec: IndexSpec<P>,
  views: readonly P[],
  numbering: Numbering,
): string {
  const groups: P[][] = spec.groups.map(() => []);
  for (const view of views) {
    const at = spec.groups.findIndex((g) => g.filter(view));
    if (at >= 0) groups[at]?.push(view);
  }
  const lines = [
    `<!-- Generated by ${spec.tool}; do not edit. Run \`${spec.tool} index\` to update it. -->`,
    `# ${spec.title}`,
    "",
  ];
  spec.groups.forEach((g, i) => {
    const members = groups[i] ?? [];
    if (members.length === 0) return;
    lines.push(
      `## ${g.heading}`,
      "",
      row(spec.columns.map((c) => c.heading)),
      row(spec.columns.map(() => "---")),
      ...[...members].sort(spec.order).map((p) => row(spec.columns.map((c) => c.cell(p)))),
      "",
    );
  });
  if (groups.every((g) => g.length === 0)) lines.push("No entries yet.", "");
  lines.push(numbersLine(numbering));
  return `${lines.join("\n")}\n`;
}

function numbersLine(numbering: Numbering): string {
  if (!numbering.available) return `${NUMBERS_PREFIX} unavailable -->`;
  const entries = [...numbering.byId].sort(([, a], [, b]) => a - b);
  return `${NUMBERS_PREFIX}${entries.map(([id, n]) => ` ${id}=${n}`).join("")} -->`;
}

/**
 * The numbers an index recorded: its last numbers line, parsed. `null` when there is none, it says
 * `unavailable`, it is malformed, or an id or a number repeats. Never throws.
 */
export function parseIndexNumbers(text: string): ReadonlyMap<string, number> | null {
  const line = text
    .split("\n")
    .map((l) => l.replace(/\r$/, ""))
    .findLast((l) => l.startsWith(NUMBERS_PREFIX));
  const m = line === undefined ? null : NUMBERS_LINE.exec(line);
  if (m === null) return null;
  const numbers = new Map<string, number>();
  const used = new Set<number>();
  for (const entry of (m[1] ?? "").split(" ").slice(1)) {
    const [id = "", n = ""] = entry.split("=");
    const number = Number(n);
    if (numbers.has(id) || used.has(number)) return null;
    numbers.set(id, number);
    used.add(number);
  }
  return numbers;
}

/**
 * `parseIndexNumbers` of the file at `path` in `tree`; `null` for a missing file or one over
 * 4 MiB.
 */
export async function readIndexNumbers(
  tree: TreeReader,
  path: string,
): Promise<ReadonlyMap<string, number> | null> {
  const bytes = await tree.read(path);
  if (bytes === null || bytes.byteLength > MAX_INDEX_BYTES) return null;
  return parseIndexNumbers(new TextDecoder().decode(bytes));
}
