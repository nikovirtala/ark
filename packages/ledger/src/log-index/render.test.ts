import fc from "fast-check";
import { describe, expect, it } from "vitest";
import { NO_INDEX_NUMBERING, NO_NUMBERING, type Numbering } from "../fold/numbering.js";
import { MemoryTree } from "../git/tree.js";
import { arbSubjectId } from "../testing/arbitraries.js";
import {
  escapeMarkdown,
  type IndexSpec,
  indexNumbering,
  parseIndexNumbers,
  readIndexNumbers,
  renderIndex,
} from "./render.js";

interface Row {
  readonly id: string;
  readonly title: string;
  readonly status: "accepted" | "proposed" | "rejected" | "draft";
  readonly n: number | null;
}

const spec: IndexSpec<Row> = {
  tool: "adr",
  title: "Architecture decisions",
  groups: [
    { heading: "Accepted", filter: (r) => r.status === "accepted" },
    { heading: "Proposed", filter: (r) => r.status === "proposed" },
    { heading: "Rejected", filter: (r) => r.status === "rejected" },
  ],
  columns: [
    { heading: "Decision", cell: (r) => (r.n === null ? r.id : `ADR-${r.n}`) },
    { heading: "Title", cell: (r) => escapeMarkdown(r.title) },
    { heading: "Status", cell: (r) => r.status },
  ],
  order: (a, b) => (a.n ?? Infinity) - (b.n ?? Infinity) || (a.id < b.id ? -1 : 1),
};

const numbering = (byId: Record<string, number>): Numbering => ({
  available: true,
  reason: null,
  ref: null,
  commit: null,
  byId: new Map(Object.entries(byId)),
  byNumber: new Map(Object.entries(byId).map(([id, n]) => [n, id])),
});

const HEADER = "<!-- Generated by adr; do not edit. Run `adr index` to update it. -->";

describe("renderIndex", () => {
  it("renders non-empty groups in order, rows by spec order, and the numbers line", () => {
    const rows: Row[] = [
      { id: "cccccccc", title: "Use Aurora", status: "accepted", n: 2 },
      { id: "aaaaaaaa", title: "Use DynamoDB", status: "accepted", n: 1 },
      { id: "dddddddd", title: "Use SQS", status: "rejected", n: null },
      { id: "eeeeeeee", title: "Hidden", status: "draft", n: null },
      { id: "bbbbbbbb", title: "Use k3s", status: "proposed", n: null },
    ];
    expect(renderIndex(spec, rows, numbering({ cccccccc: 2, aaaaaaaa: 1 }))).toBe(
      [
        HEADER,
        "# Architecture decisions",
        "",
        "## Accepted",
        "",
        "| Decision | Title | Status |",
        "| --- | --- | --- |",
        "| ADR-1 | Use DynamoDB | accepted |",
        "| ADR-2 | Use Aurora | accepted |",
        "",
        "## Proposed",
        "",
        "| Decision | Title | Status |",
        "| --- | --- | --- |",
        "| bbbbbbbb | Use k3s | proposed |",
        "",
        "## Rejected",
        "",
        "| Decision | Title | Status |",
        "| --- | --- | --- |",
        "| dddddddd | Use SQS | rejected |",
        "",
        "<!-- ledger-index/v1 numbers: aaaaaaaa=1 cccccccc=2 -->",
        "",
      ].join("\n"),
    );
  });

  it("omits empty groups and keeps each row on one line", () => {
    const rows: Row[] = [{ id: "bbbbbbbb", title: "x", status: "proposed", n: null }];
    const raw: IndexSpec<Row> = { ...spec, columns: [{ heading: "Raw", cell: () => "a\nb\r\nc" }] };
    const text = renderIndex(raw, rows, numbering({}));
    expect(text).not.toContain("## Accepted");
    expect(text).toContain("| Raw |\n| --- |\n| a b c |\n");
  });

  it("renders an empty log", () => {
    expect(renderIndex(spec, [], numbering({}))).toBe(
      `${HEADER}\n# Architecture decisions\n\nNo entries yet.\n\n<!-- ledger-index/v1 numbers: -->\n`,
    );
  });

  it("records unavailable numbers so they parse as none", () => {
    const text = renderIndex(spec, [], { ...NO_NUMBERING, reason: "shallow" });
    expect(text.endsWith("\n<!-- ledger-index/v1 numbers: unavailable -->\n")).toBe(true);
    expect(parseIndexNumbers(text)).toBeNull();
  });
});

describe("escapeMarkdown", () => {
  it("escapes table, link, emphasis and HTML characters, and collapses whitespace", () => {
    expect(escapeMarkdown("a | b")).toBe("a \\| b");
    expect(escapeMarkdown("[x](y)")).toBe("\\[x\\](y)");
    expect(escapeMarkdown("<!-- hidden -->")).toBe("\\<!-- hidden --\\>");
    expect(escapeMarkdown(" *a*  _b_\n`c` \\ ")).toBe("\\*a\\* \\_b\\_ \\`c\\` \\\\");
  });

  it("keeps an escaped title inside its cell", () => {
    const rows: Row[] = [{ id: "aaaaaaaa", title: "a | [b] <!-- c", status: "accepted", n: 1 }];
    const text = renderIndex(spec, rows, numbering({ aaaaaaaa: 1 }));
    expect(text).toContain("| ADR-1 | a \\| \\[b\\] \\<!-- c | accepted |\n");
    expect(parseIndexNumbers(text)).toEqual(new Map([["aaaaaaaa", 1]]));
  });
});

describe("parseIndexNumbers", () => {
  it("reads back what renderIndex records", () => {
    const arbNumbering = fc
      .uniqueArray(fc.tuple(arbSubjectId(), fc.integer({ min: 1, max: 999_999_999 })), {
        selector: ([id]) => id,
        maxLength: 20,
      })
      .filter((pairs) => new Set(pairs.map(([, n]) => n)).size === pairs.length);
    fc.assert(
      fc.property(arbNumbering, (pairs) => {
        const n = numbering(Object.fromEntries(pairs));
        expect(parseIndexNumbers(renderIndex(spec, [], n))).toEqual(n.byId);
      }),
    );
  });

  it("uses the last numbers line", () => {
    const text =
      "<!-- ledger-index/v1 numbers: aaaaaaaa=1 -->\n<!-- ledger-index/v1 numbers: bbbbbbbb=2 -->\n";
    expect(parseIndexNumbers(text)).toEqual(new Map([["bbbbbbbb", 2]]));
  });

  it.each([
    ["a duplicate id", "<!-- ledger-index/v1 numbers: aaaaaaaa=1 aaaaaaaa=2 -->"],
    ["a duplicate number", "<!-- ledger-index/v1 numbers: aaaaaaaa=1 bbbbbbbb=1 -->"],
    ["n=0", "<!-- ledger-index/v1 numbers: aaaaaaaa=0 -->"],
    ["an uppercase id", "<!-- ledger-index/v1 numbers: AAAAAAAA=1 -->"],
    ["a missing line", "# Architecture decisions\n"],
    [
      "a malformed last line",
      "<!-- ledger-index/v1 numbers: aaaaaaaa=1 -->\n<!-- ledger-index/v1 numbers: x -->",
    ],
  ])("returns null for %s", (_, text) => {
    expect(parseIndexNumbers(text)).toBeNull();
  });
});

describe("readIndexNumbers", () => {
  it("reads a file's numbers, and null for a missing file or one over 4 MiB", async () => {
    const line = "<!-- ledger-index/v1 numbers: aaaaaaaa=1 -->\n";
    const tree = new MemoryTree({
      "log/index.md": line,
      "log/big.md": `${"x".repeat(4 * 1024 * 1024)}\n${line}`,
    });
    expect(await readIndexNumbers(tree, "log/index.md")).toEqual(new Map([["aaaaaaaa", 1]]));
    expect(await readIndexNumbers(tree, "log/missing.md")).toBeNull();
    expect(await readIndexNumbers(tree, "log/big.md")).toBeNull();
  });
});

describe("indexNumbering", () => {
  it("is NO_INDEX_NUMBERING without an index", () => {
    expect(indexNumbering(null)).toBe(NO_INDEX_NUMBERING);
  });

  it("turns the index's numbers into a Numbering", () => {
    const byId = new Map([
      ["aaaaaaaa", 1],
      ["bbbbbbbb", 2],
    ]);
    expect(indexNumbering(byId)).toEqual({
      available: true,
      reason: "index",
      ref: null,
      commit: null,
      byId,
      byNumber: new Map([
        [1, "aaaaaaaa"],
        [2, "bbbbbbbb"],
      ]),
    });
  });
});
