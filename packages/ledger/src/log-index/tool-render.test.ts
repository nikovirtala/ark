import { execFile } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { promisify } from "node:util";
import { afterEach, describe, expect, it } from "vitest";
import type { Numbering } from "../fold/numbering.js";
import { Git } from "../git/git.js";
import { refReader, type TreeReader, worktreeReader } from "../git/tree.js";
import { exampleMachineKind as kind } from "../testing/example-machine-kind.js";
import { createTempRepo, type TempRepo } from "../testing/temp-repo.js";
import { escapeMarkdown, type IndexSpec } from "./render.js";
import { indexPath, renderLogIndex, unstagedIndexText, unstagedLogFiles } from "./tool-render.js";

const run = promisify(execFile);
const layout = kind.layoutAt("log");
const A = "aaaaaaaa";
const B = "bbbbbbbb";
const C = "cccccccc";

const repos: TempRepo[] = [];
afterEach(async () => {
  for (const r of repos.splice(0)) await r.dispose();
});
async function repo(files?: Record<string, string>): Promise<TempRepo> {
  const r = await createTempRepo(files === undefined ? {} : { files });
  repos.push(r);
  return r;
}

/** A `published` event file of `subject`; the numbering reads only its path. */
const published = (subject: string, day: number) =>
  `log/events/${subject}/202601${String(day).padStart(2, "0")}T000000Z-0000-published.yaml`;

interface View {
  readonly id: string;
  readonly display: string;
}

/** The subjects with events in `tree`, displayed with their numbers. */
async function views(tree: TreeReader, numbering: Numbering): Promise<View[]> {
  const ids = new Set(
    (await tree.list("log/events")).map((e) => e.path.split("/")[2] ?? "").filter((x) => x),
  );
  return [...ids].map((id) => {
    const n = numbering.byId.get(id);
    return { id, display: n === undefined ? id : `W-${n}` };
  });
}

const spec = (root: string, vs: readonly View[]): IndexSpec<View> => ({
  tool: "widget",
  title: `Widgets in ${root} (${vs.length})`,
  groups: [{ heading: "All", filter: () => true }],
  columns: [
    { heading: "Widget", cell: (v) => escapeMarkdown(v.display) },
    { heading: "Id", cell: (v) => v.id },
  ],
  order: (a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0),
});

const render = (git: Git, tree: TreeReader, history: string | null) =>
  renderLogIndex(git, { kind, layout, mainRef: null, tree, history, views, spec });

describe("indexPath", () => {
  it("is index.md in the log's root", () => {
    expect(indexPath(layout)).toBe("log/index.md");
  });
});

describe("renderLogIndex", () => {
  it("renders the spec of the tree's views, numbered as they will be on main", async () => {
    const r = await repo({ [published(B, 1)]: "x\n" });
    await r.write(published(A, 2), "x\n");
    const text = await render(r.git, worktreeReader(r.git), await r.git.resolveCommit("HEAD"));
    expect(text).toBe(
      [
        "<!-- Generated by widget; do not edit. Run `widget index` to update it. -->",
        "# Widgets in log (2)",
        "",
        "## All",
        "",
        "| Widget | Id |",
        "| --- | --- |",
        `| W-2 | ${A} |`,
        `| W-1 | ${B} |`,
        "",
        `<!-- ledger-index/v1 numbers: ${B}=1 ${A}=2 -->`,
        "",
      ].join("\n"),
    );
  });

  it("numbers MERGE_HEAD's subjects while a merge is in progress", async () => {
    const r = await repo({ "README.md": "x\n" });
    await r.checkout("feature", { create: true });
    await r.write(published(A, 1), "x\n");
    await r.stage(published(A, 1));
    await r.commit("feature");
    await r.checkout("main");
    await r.write(published(C, 2), "x\n");
    await r.stage(published(C, 2));
    await r.commit("main");
    await r.checkout("feature");
    await r.git.run(["merge", "-q", "--no-ff", "--no-commit", "main"]);
    // Merging main puts main's acceptances first; without MERGE_HEAD, C would be pending, so last.
    const text = await render(r.git, worktreeReader(r.git), await r.git.resolveCommit("HEAD"));
    expect(text).toContain(`<!-- ledger-index/v1 numbers: ${C}=1 ${A}=2 -->`);
  });

  it("continues the numbers of history's index in a shallow clone, else returns null", async () => {
    const r = await repo({ [published(A, 1)]: "x\n" });
    const head = await r.git.resolveCommit("HEAD");
    await r.write(
      "log/index.md",
      (await render(r.git, await refReader(r.git, "HEAD"), head)) ?? "",
    );
    await r.stage("log/index.md");
    await r.commit("index");
    const clone = async (name: string) => {
      const dest = join(r.root, "..", name);
      const env = { ...process.env, ...r.git.options.env } as Record<string, string>;
      await run("git", ["clone", "-q", "--depth", "1", `file://${r.root}`, dest], { env });
      return { git: await Git.open(dest, r.git.options), dest };
    };
    const shallow = await clone("shallow");
    await mkdir(join(shallow.dest, `log/events/${B}`), { recursive: true });
    await writeFile(join(shallow.dest, published(B, 2)), "x\n");
    const tip = await shallow.git.resolveCommit("HEAD");
    const text = await render(shallow.git, worktreeReader(shallow.git), tip);
    expect(text).toContain(`<!-- ledger-index/v1 numbers: ${A}=1 ${B}=2 -->`);

    await r.git.run(["rm", "-q", "log/index.md"]);
    await r.commit("drop the index");
    const without = await clone("shallow-without-index");
    const at = await without.git.resolveCommit("HEAD");
    expect(await render(without.git, worktreeReader(without.git), at)).toBeNull();
  });
});

describe("unstagedIndexText", () => {
  it("names the files with the noun", () => {
    expect(unstagedIndexText("log/index.md", ["a", "b"], "widget")).toBe(
      "log/index.md lists widget files that aren't staged (a, b)",
    );
  });

  it("names the first five files", () => {
    const five = ["1", "2", "3", "4", "5"];
    expect(unstagedIndexText("i.md", five, "issue")).toBe(
      "i.md lists issue files that aren't staged (1, 2, 3, 4, 5)",
    );
    expect(unstagedIndexText("i.md", [...five, "6"], "decision")).toBe(
      "i.md lists decision files that aren't staged (1, 2, 3, 4, 5, …)",
    );
  });
});

describe("unstagedLogFiles", () => {
  it("lists the log's modified and untracked event and body files, sorted", async () => {
    const r = await repo({
      [published(B, 1)]: "x\n",
      [`log/items/${B}.md`]: "body\n",
      "log/index.md": "old\n",
      "other.txt": "x\n",
    });
    await r.write(published(B, 1), "changed\n");
    await r.write(published(A, 2), "x\n");
    await r.write(`log/items/${A}.md`, "body\n");
    await r.write("log/index.md", "new\n");
    await r.write("log/widget.toml", "\n");
    await r.write("other.txt", "y\n");
    await r.write("new.txt", "y\n");
    await r.write(`log/items/${B}.md`, "staged\n");
    await r.stage(`log/items/${B}.md`);
    expect(await unstagedLogFiles(r.git, layout)).toEqual([
      published(A, 2),
      published(B, 1),
      `log/items/${A}.md`,
    ]);
  });

  it("is empty when everything is staged", async () => {
    const r = await repo({ [published(A, 1)]: "x\n" });
    await r.write(published(B, 2), "x\n");
    await r.stage(published(B, 2));
    expect(await unstagedLogFiles(r.git, layout)).toEqual([]);
  });
});
