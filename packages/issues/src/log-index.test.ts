import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { newSubjectId, refReader } from "@nikovirtala/ledger";
import { createTempRepo, type TempRepo } from "@nikovirtala/ledger/testing";
import { afterEach, describe, expect, it } from "vitest";
import { DEFAULT_ISSUES_CONFIG } from "./config.js";
import { openIssueLog, readIssues } from "./log.js";
import { indexIssueLog, renderIssueIndex } from "./log-index.js";
import { issueEvent, issueFiles, LAYOUT, opened, type SubjectSpec } from "./test-support/events.js";

const repos: TempRepo[] = [];
afterEach(async () => {
  for (const r of repos.splice(0)) await r.dispose();
});
async function repo(files: Record<string, string>): Promise<TempRepo> {
  const r = await createTempRepo({ files: { "README.md": "readme\n", ...files } });
  repos.push(r);
  return r;
}

const COMMITTED = { ...DEFAULT_ISSUES_CONFIG, index: "committed" as const };
const ids = Array.from({ length: 30 }, () => newSubjectId());
const [WORKING, READY, BLOCKED, ASSIGNED, PIPE] = ids as [string, string, string, string, string];
const CLOSED = ids.slice(5, 26);

/** One issue per group, a title with a |, and 21 closed issues closed a minute apart. */
function fixture(): SubjectSpec[] {
  return [
    {
      id: WORKING,
      events: [opened(WORKING, "Split the orders service"), issueEvent(WORKING, "started")],
    },
    { id: READY, events: [opened(READY, "Extract the consumer")] },
    {
      id: BLOCKED,
      events: [
        opened(BLOCKED, "Move the schema"),
        issueEvent(BLOCKED, "linked", { data: { to: READY, rel: "depends-on" } }),
      ],
    },
    {
      id: ASSIGNED,
      events: [
        opened(ASSIGNED, "Assigned, not started"),
        issueEvent(ASSIGNED, "assigned", { data: { set: ["ada@example.com"] } }),
        issueEvent(ASSIGNED, "labeled", { data: { set: ["type:bug", "priority:high"] } }),
      ],
    },
    { id: PIPE, events: [opened(PIPE, "Use a | in a title")] },
    ...CLOSED.map((id, i) => ({
      id,
      events: [
        opened(id, `Closed ${i}`),
        issueEvent(id, "closed", {
          data: { resolution: "done" },
          at: `2026-10-25T10:${String(i).padStart(2, "0")}:00Z`,
        }),
      ],
    })),
  ];
}

const rows = (text: string, heading: string): string[] => {
  const section = text.split(`## ${heading}\n`)[1]?.split("\n## ")[0] ?? "";
  return section
    .split("\n")
    .filter((l) => l.startsWith("| ") && !l.startsWith("| Issue") && !l.startsWith("| ---"));
};

describe("renderIssueIndex", () => {
  it("groups issues, escapes cells, numbers them and keeps the 20 latest closed", async () => {
    const r = await repo(issueFiles(fixture()));
    const head = (await r.git.resolveCommit("HEAD")) ?? "";
    const text =
      (await renderIssueIndex(r.git, {
        layout: LAYOUT,
        issues: COMMITTED,
        tree: await refReader(r.git, head),
        history: head,
      })) ?? "";
    expect(text.startsWith("<!-- Generated by issues")).toBe(true);
    expect([...text.matchAll(/^## (.+)$/gm)].map((m) => m[1])).toEqual([
      "In progress",
      "Ready",
      "Blocked",
      "Open",
      "Recently closed",
    ]);
    expect(text).toContain("| Issue | Title | Assignees | Labels | Since |");
    expect(rows(text, "In progress")).toHaveLength(1);
    expect(rows(text, "In progress")[0]).toMatch(/\[Split the orders service\]\(items\//);
    const ready = rows(text, "Ready");
    expect(
      ready.map((l) => l.includes("Extract the consumer") || l.includes("Use a \\| in")),
    ).toEqual([true, true]);
    expect(rows(text, "Blocked")[0]).toContain("Move the schema");
    const open = rows(text, "Open");
    expect(open).toHaveLength(1);
    expect(open[0]).toContain("| ada@example.com | type:bug, priority:high |");
    const closed = rows(text, "Recently closed");
    expect(closed).toHaveLength(20);
    expect(text).not.toContain("Closed 0]");
    expect(text).toContain("Closed 20]");
    // Numbers from main's history, every row shown by its number.
    expect(rows(text, "Ready")[0]).toMatch(/^\| \?\d+ \|/);
  });
});

describe("numbers in a shallow clone", () => {
  it("come from the committed index.md", async () => {
    const r = await repo({
      ...issueFiles(fixture().slice(0, 3)),
      "docs/issues/issues.toml": '[log]\nindex = "committed"\n',
    });
    const log = await openIssueLog({ cwd: r.root, gitOptions: { env: r.env } });
    await indexIssueLog(log, { commit: true });
    const full = (await readIssues(log)).projection.views;
    const shallow = join(r.root, "..", "shallow");
    const clone = spawnSync("git", ["clone", "-q", "--depth", "1", `file://${r.root}`, shallow], {
      env: r.env,
      encoding: "utf8",
    });
    expect(clone.status, clone.stderr).toBe(0);
    const read = await readIssues(await openIssueLog({ cwd: shallow, gitOptions: { env: r.env } }));
    expect(read.numbering).toMatchObject({ available: true, reason: "index" });
    for (const [id, v] of full) expect(read.projection.views.get(id)?.display).toBe(v.display);
  });
});
